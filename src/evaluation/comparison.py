"""The model comparison table: why one family was chosen, not just that it was.

Built from the leaderboard the training run recorded, so it is a view over
measured data rather than a second place where numbers are typed in and drift.
Cost columns sit beside accuracy on purpose — a family that ties on MAE while
taking twenty times as long to fit, or producing a model forty times the size,
lost for a reason no accuracy column can show.
"""

from __future__ import annotations

import pandas as pd

from src.models.artifact import ModelArtifact

DISPLAY_NAMES = {
    "linear": "Linear Regression",
    "ridge": "Ridge",
    "lasso": "Lasso",
    "elastic_net": "ElasticNet",
    "random_forest": "Random Forest",
    "extra_trees": "Extra Trees",
    "gradient_boosting": "GradientBoosting (hist)",
    "xgboost": "XGBoost",
    "lightgbm": "LightGBM",
    "catboost": "CatBoost",
    "stacked": "Stacked (LGBM+XGB+Cat)",
}


def comparison_frame(artifact: ModelArtifact) -> pd.DataFrame:
    """One row per family, ordered by the selection metric."""
    rows = []
    for entry in artifact.leaderboard:
        predict_rows = entry.get("predict_rows") or 1
        predict_seconds = entry.get("predict_seconds", float("nan"))
        rows.append(
            {
                "model": DISPLAY_NAMES.get(entry["model"], entry["model"]),
                "val MAE (EUR)": round(entry["validation_mae_eur"]),
                "val RMSE (EUR)": round(entry.get("validation_rmse_eur", float("nan"))),
                "val R²": round(entry["validation_r2"], 3),
                "val MAPE": f"{entry.get('validation_mape', float('nan')):.1%}",
                "cv MAE (EUR)": round(entry.get("cv_mae_eur", float("nan"))),
                "train (s)": round(entry.get("fit_seconds", float("nan")), 2),
                # Per-1k rows, so the number is comparable across variants whose
                # validation seasons hold different numbers of players.
                "predict (ms/1k)": round(predict_seconds / predict_rows * 1e6, 1),
                "size (MB)": round(entry.get("size_bytes", 0) / 1024 / 1024, 2),
                "selected": "yes" if entry["model"] == artifact.model_name else "",
            }
        )
    return pd.DataFrame(rows)


def _markdown_table(frame: pd.DataFrame) -> list[str]:
    header = "| " + " | ".join(frame.columns) + " |"
    divider = "|" + "|".join("---" for _ in frame.columns) + "|"
    rows = [
        "| "
        + " | ".join(
            f"{value:,}" if isinstance(value, int | float) else str(value) for value in row
        )
        + " |"
        for row in frame.itertuples(index=False)
    ]
    return [header, divider, *rows]


def build_comparison_document(artifacts: list[ModelArtifact]) -> str:
    """Render docs/model_comparison.md from the trained artifacts."""
    lines = [
        "# Model comparison",
        "",
        "Generated by `python scripts/build_reports.py` from the saved artifacts.",
        "Every figure is measured, not quoted — rerun the command to refresh it.",
        "",
        "All families are trained on the same rows, the same split and the same",
        "seed, and ranked by **validation MAE in EUR**, which is the selection",
        "metric (see [EXPERIMENT_TRACKING.md](EXPERIMENT_TRACKING.md) §4). Test",
        "metrics are not shown per family on purpose: the test seasons are",
        "touched once, by the winner only. Ranking every family on test would",
        "make the test set a second validation set.",
        "",
        "Timings are wall-clock on one machine for one fit of the tuned",
        "configuration, so they are comparable to each other and not to any",
        "other machine.",
        "",
    ]

    for artifact in artifacts:
        frame = comparison_frame(artifact)
        lines += [
            f"## {artifact.variant}",
            "",
            f"Winner: **{DISPLAY_NAMES.get(artifact.model_name, artifact.model_name)}** "
            f"— test MAE €{artifact.test.mae:,.0f}, test R² {artifact.test.r2:.3f} "
            f"over {artifact.test.n:,} rows.",
            "",
            *_markdown_table(frame),
            "",
        ]

    lines += [
        "## Reading this table",
        "",
        *_observations(artifacts[0]),
        "- **`val MAE` selects; `cv MAE` explains.** The cross-validation column",
        "  is the mean across expanding-window folds inside the training",
        "  seasons. A family that looks good on one and poor on the other was",
        "  lucky or unlucky on the single validation season.",
        "",
    ]
    return "\n".join(lines)


def _observations(artifact: ModelArtifact) -> list[str]:
    """Findings computed from the leaderboard, not typed in.

    Hardcoded prose about a measured table is prose that quietly becomes false
    the next time the table is regenerated. These sentences are rebuilt from
    the same numbers the rows are.
    """
    board = sorted(artifact.leaderboard, key=lambda row: row["validation_mae_eur"])
    if not board:
        return []

    best, worst = board[0], board[-1]
    spread = (worst["validation_mae_eur"] / best["validation_mae_eur"] - 1) * 100
    notes = [
        f"- **The spread is narrow.** Best to worst is {spread:.0f}% on the "
        f"selection metric across {len(board)} families. The signal in this data is in "
        "the features, not the estimator — which is exactly why the Phase 6 "
        "baseline was measured before any of this was built.",
    ]

    # The cheapest family that is within 1% of the winner on accuracy. If one
    # exists, the choice was closer than the ranking suggests and saying so is
    # more useful than presenting the winner as obvious.
    close = [
        row
        for row in board[1:]
        if row["validation_mae_eur"] <= best["validation_mae_eur"] * 1.01
        and row.get("size_bytes", 0) < best.get("size_bytes", 0)
        and row.get("fit_seconds", 0) < best.get("fit_seconds", 0)
    ]
    if close:
        runner = min(close, key=lambda row: row["size_bytes"])
        gap = (runner["validation_mae_eur"] / best["validation_mae_eur"] - 1) * 100
        notes.append(
            f"- **The choice was close.** "
            f"{DISPLAY_NAMES.get(runner['model'], runner['model'])} costs "
            f"{gap:.2f}% more error for "
            f"{best['fit_seconds'] / max(runner['fit_seconds'], 1e-9):.1f}x faster "
            f"training and "
            f"{best['size_bytes'] / max(runner['size_bytes'], 1):.1f}x less disk. "
            "On this evidence it is a defensible alternative, and if serving "
            "cost ever matters it is the one to switch to."
        )

    largest = max(board, key=lambda row: row.get("size_bytes", 0))
    if largest["model"] != best["model"] and largest.get("size_bytes"):
        ratio = largest["size_bytes"] / max(best.get("size_bytes", 1), 1)
        notes.append(
            f"- **Cost breaks ties, and sometimes it is not close.** "
            f"{DISPLAY_NAMES.get(largest['model'], largest['model'])} serialises "
            f"to {largest['size_bytes'] / 1024 / 1024:,.0f} MB against the "
            f"winner's {best['size_bytes'] / 1024 / 1024:,.1f} MB — {ratio:,.0f}x "
            "larger — while scoring worse. Accuracy columns alone would not "
            "show why it was never a candidate."
        )
    return notes
